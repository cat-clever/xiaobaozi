/**
 * MD5（RFC 1321）—— 纯 TypeScript 实现。
 *
 * 上游两个源都要用它：
 *   - 源1：请求签名头 `sign = MD5(SIGN_SALT + device_id + cur_time)`（大写 hex）
 *          以及 CDN 签名 `wsSecret = MD5(ws_key + path + wsTime_hex)`（小写 hex）
 *   - 源2：设备号摘要 `udid = MD5(uid)`，以及密钥派生的两步摘要
 *
 * 实现与 `参考/影视站api2.js` 中的版本逐字节对齐（同一套常量与轮函数），
 * 单元测试用 Node 内置 crypto 的 md5 交叉验证。
 */

